// MaxGeneratedFonts bounds how many missing TFMs one build may ask mktextfm to generate
// (decision 158).
const MaxGeneratedFonts = 40

const mktextfmTimeout = 30 * time.Second

var (
	missingMetricSuffix = regexp.MustCompile(`not loadable: (?:metric data not found or bad|Metric \(TFM\) file not found)\.\z`)
	missingFontLine     = regexp.MustCompile(`\A! Font \\[^=]+=(.+?)(?: (?:at|scaled) .+?)? not loadable: (?:metric data not found or bad|Metric \(TFM\) file not found)\.`)
	safeTFMName         = regexp.MustCompile(`\A[A-Za-z0-9_-]+\z`)
)

// GeneratedFontsDir is the shared cache directory holding TFMs generated by mktextfm
// (decision 158).
func GeneratedFontsDir() string {
	return filepath.Join(command.CacheRoot(), "texmf-generated")
}

// GeneratedFontsSearchTree is GeneratedFontsDir formatted as a kpathsea TEXMFAUXTREES entry.
func GeneratedFontsSearchTree() string {
	return filepath.ToSlash(GeneratedFontsDir()) + ","
}

// WithGeneratedFonts returns a copy of environment with TEXMFAUXTREES pointing at
// GeneratedFontsDir so LuaLaTeX and kpsewhich search generated TFMs without replacing the
// build's private TEXMFVAR.
func WithGeneratedFonts(environment map[string]string) map[string]string {
	merged := maps.Clone(environment)
	if merged == nil {
		merged = map[string]string{}
	}
	merged["TEXMFAUXTREES"] = GeneratedFontsSearchTree()
	return merged
}

// MissingMetricFonts returns the unique safe TFM font names named in LuaLaTeX missing-metric
// errors in logText, in order of appearance, unwrapping TeX's 79-column log wraps.
func MissingMetricFonts(logText string) []string {
	lines := strings.Split(strings.ReplaceAll(logText, "\r\n", "\n"), "\n")
	names := []string{}
	for index := 0; index < len(lines); index++ {
		if !strings.HasPrefix(lines[index], "! Font ") {
			continue
		}
		message := joinWrappedFontError(lines, index)
		match := missingFontLine.FindStringSubmatch(message)
		if match == nil || !safeTFMName.MatchString(match[1]) || slices.Contains(names, match[1]) {
			continue
		}
		names = append(names, match[1])
	}
	return names
}

func joinWrappedFontError(lines []string, start int) string {
	message := lines[start]
	for offset := 1; offset <= 3 && start+offset < len(lines); offset++ {
		if missingMetricSuffix.MatchString(message) {
			break
		}
		nextLine := lines[start+offset]
		if nextLine == "" || strings.HasPrefix(nextLine, "! ") || strings.HasPrefix(nextLine, "<") || strings.HasPrefix(nextLine, "l.") {
			break
		}
		message += nextLine
	}
	return message
}

// FontGenerator tracks per-build attempts to generate missing TFMs with mktextfm so retries are
// bounded and never loop.
type FontGenerator struct {
	Engine       string
	GeneratedDir string
	Limit        int
	Attempted    map[string]bool
	Generated    []string
	Ensure       func(name string, timeout time.Duration) (created, available bool)
}

// NewFontGenerator creates a bounded FontGenerator for engine writing to GeneratedFontsDir.
func NewFontGenerator(engine string) *FontGenerator {
	return &FontGenerator{
		Engine:       engine,
		GeneratedDir: GeneratedFontsDir(),
		Limit:        MaxGeneratedFonts,
		Attempted:    map[string]bool{},
	}
}

// Recover inspects logText for missing TFM fonts, generates any unattempted candidates up to
// Limit before deadline, and reports whether the pass should be rerun.
func (g *FontGenerator) Recover(logText string, deadline time.Time) bool {
	if g.Attempted == nil {
		g.Attempted = map[string]bool{}
	}
	limit := g.Limit
	if limit <= 0 {
		limit = MaxGeneratedFonts
	}
	if len(g.Attempted) >= limit {
		return false
	}
	ensure := g.Ensure
	if ensure == nil {
		ensure = g.ensureTFM
	}
	retry := false
	for _, name := range MissingMetricFonts(logText) {
		if g.Attempted[name] || len(g.Attempted) >= limit {
			continue
		}
		timeout := remainingStepTimeout(deadline)
		if timeout <= 0 {
			break
		}
		g.Attempted[name] = true
		created, available := ensure(name, timeout)
		if created {
			g.Generated = append(g.Generated, name)
		}
		if available {
			retry = true
		}
	}
	return retry
}

// RunPass runs step repeatedly while it stops without timing out on missing TFMs and Recover
// generates or finds at least one new font before deadline. When non-nil, onRetry runs before
// each rerun.
func (g *FontGenerator) RunPass(logPath string, deadline time.Time, step func() rec.Map, onRetry func()) rec.Map {
	for {
		stage := step()
		if g == nil || rec.Equal(stage["exit"], int64(0)) || stage["timeout"] == true {
			return stage
		}
		data, err := os.ReadFile(logPath)
		if err != nil || !g.Recover(strings.ToValidUTF8(string(data), "\uFFFD"), deadline) {
			return stage
		}
		if onRetry != nil {
			onRetry()
		}
	}
}

func remainingStepTimeout(deadline time.Time) time.Duration {
	if deadline.IsZero() {
		return mktextfmTimeout
	}
	left := time.Until(deadline)
	if left <= 0 {
		return 0
	}
	return min(mktextfmTimeout, left)
}

func (g *FontGenerator) ensureTFM(name string, timeout time.Duration) (created, available bool) {
	mkdir(g.GeneratedDir)
	lock, err := os.OpenFile(filepath.Join(g.GeneratedDir, "build.lock"), os.O_RDWR|os.O_CREATE, 0o644)
	if err != nil {
		rec.Fail("%v", err)
	}
	defer lock.Close()
	if lockErr := lockfile.Lock(lock); lockErr != nil {
		rec.Fail("%v", lockErr)
	}
	if hasTFM(g.GeneratedDir, name) {
		return false, true
	}
	tool := command.Sibling(g.Engine, "mktextfm")
	if !command.IsExecutable(tool) {
		return false, false
	}
	scratch := command.Scratch("mktextfm-")
	defer os.RemoveAll(scratch)
	environment := map[string]string{
		"PATH":          command.ToolPath(g.Engine),
		"TEXMFVAR":      g.GeneratedDir,
		"TEXMFAUXTREES": filepath.ToSlash(g.GeneratedDir) + ",",
		"TEXMFCACHE":    scratch,
		"TMPDIR":        scratch,
		"TMP":           scratch,
		"TEMP":          scratch,
	}
	stage := command.Run([]string{tool, name}, scratch, filepath.Join(scratch, "mktextfm.log"), timeout, environment)
	if !rec.Equal(stage["exit"], int64(0)) || stage["timeout"] == true || !hasTFM(g.GeneratedDir, name) {
		return false, false
	}
	fmt.Fprintf(os.Stderr, "engine: mktextfm %s\n", name)
	return true, true
}

func hasTFM(root, name string) bool {
	tfmRoot := filepath.Join(root, "fonts", "tfm")
	if !isDir(tfmRoot) {
		return false
	}
	target := name + ".tfm"
	found := false
	_ = filepath.WalkDir(tfmRoot, func(_ string, entry fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if !entry.IsDir() && entry.Name() == target {
			found = true
			return fs.SkipAll
		}
		return nil
	})
	return found
}
